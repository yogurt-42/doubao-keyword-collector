#: Cached ordered list of (domain, name, category) used for matching.
_DOMAIN_ENTRIES: list[tuple[str, str, str]] = [
    (entry["domain"], entry["name"], entry["category"]) for entry in PLATFORM_ENTRIES
]

#: Reverse lookup from Chinese platform name to category.
_NAME_TO_CATEGORY: dict[str, str] = {
    entry["name"]: entry["category"] for entry in PLATFORM_ENTRIES
}


def _normalize_host(url: str) -> str:
    return (urlsplit(url).hostname or "").casefold().removeprefix("www.")


def entry_for_url(url: str) -> dict[str, str] | None:
    """Return the best matching platform entry for a URL, or None."""

    host = _normalize_host(url)
    if not host:
        return None
    for domain, name, category in _DOMAIN_ENTRIES:
        if host == domain or host.endswith(f".{domain}"):
            return {"name": name, "category": category}
    # Fallback heuristics for government and education domains.
    if host == "gov.cn" or host.endswith(".gov.cn"):
        return {"name": "政府网站", "category": "政府/官方机构"}
    if host == "edu.cn" or host.endswith(".edu.cn"):
        return {"name": "高校网站", "category": "工具/其他"}
    return None


def platform_for_url(url: str) -> str:
    """Return the Chinese platform name for a URL (hostname fallback)."""

    entry = entry_for_url(url)
    if entry:
        return entry["name"]
    host = _normalize_host(url)
    return host or "未知平台"


def category_for_url(url: str) -> str:
    """Return the platform category for a URL, or an empty string if unknown."""

    entry = entry_for_url(url)
    return entry["category"] if entry else ""


def platform_category(platform_name: str) -> str:
    """Return the category for a known Chinese platform name."""

    return _NAME_TO_CATEGORY.get(platform_name.strip(), "")


def to_js_known() -> str:
    """Return a JSON array of [domain, name] pairs for injection into JS scripts."""

    return json.dumps(
        [[domain, name] for domain, name, _ in _DOMAIN_ENTRIES],
        ensure_ascii=False,
    )


def to_js_platform_data() -> str:
    """Return a JSON object mapping domain -> [name, category] for JS scripts."""

    return json.dumps(
        {entry["domain"]: [entry["name"], entry["category"]] for entry in PLATFORM_ENTRIES},
        ensure_ascii=False,
    )
